class DirectoryIndexTests(unittest.TestCase):
    def test_generates_nested_indexes_and_preserves_manual_root(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            (site / "index.html").write_text("<h1>Branded landing page</h1>", encoding="utf-8")
            repository = site / "stable" / "x86_64"
            repository.mkdir(parents=True)
            (repository / "cambonos-1.0-1-any.pkg.tar.zst").write_bytes(b"package")
            (repository / "cambonos.db.tar.gz").write_bytes(b"database archive")
            (repository / "file with spaces.txt").write_text("content", encoding="utf-8")

            generated, skipped = generate_directory_indexes(site)

            self.assertEqual((generated, skipped), (2, 1))
            self.assertEqual(
                (site / "index.html").read_text(encoding="utf-8"),
                "<h1>Branded landing page</h1>",
            )
            channel_index = site / "stable" / "index.html"
            architecture_index = repository / "index.html"
            self.assertTrue(channel_index.is_file())
            self.assertTrue(architecture_index.is_file())
            html = architecture_index.read_text(encoding="utf-8")
            self.assertIn('href="file%20with%20spaces.txt"', html)
            self.assertIn('href="cambonos-1.0-1-any.pkg.tar.zst"', html)
            self.assertIn('href="cambonos.db.tar.gz"', html)
            self.assertIn('href="../../">Packages</a>', html)
            self.assertIn('href="../">stable/</a>', html)
            self.assertIn('<html lang="en">', html)
            self.assertIn("CambonOS Packages | /stable/x86_64/", html)
            self.assertIn("Repository files", html)
            self.assertIn("Directory contents", html)
            self.assertIn("Official CambonOS package mirror.", html)
            self.assertNotIn("Generated by CambonOS package pipeline.", html)
            self.assertIn('aria-label="Change color theme"', html)
            self.assertIn("--lime: #aefa50", html)
            self.assertIn(':root[data-theme="dark"]', html)
            self.assertIn("prefers-color-scheme: dark", html)
            self.assertIn('class="theme-toggle"', html)
            self.assertIn('localStorage.setItem("cambonos-theme", preference)', html)
            self.assertIn('href="#main-content"', html)
            self.assertIn("cambonos-1.0-1-any.pkg.tar.zst", html)
            self.assertIn("generated-by: cambonos-index", html)

    def test_updates_generated_indexes_but_keeps_manual_nested_indexes(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            (site / "metadata").mkdir()
            (site / "metadata" / "index.html").write_text(
                "<h1>Manual metadata page</h1>", encoding="utf-8"
            )
            generated_dir = site / "stable"
            generated_dir.mkdir()
            generated_index = generated_dir / "index.html"
            generated_index.write_text(
                "<!-- generated-by: cambonos-index --><p>old</p>", encoding="utf-8"
            )
            (generated_dir / "new.db").write_bytes(b"db")

            generated, skipped = generate_directory_indexes(site)

            self.assertEqual((generated, skipped), (2, 1))
            self.assertIn("new.db", generated_index.read_text(encoding="utf-8"))
            self.assertEqual(
                (site / "metadata" / "index.html").read_text(encoding="utf-8"),
                "<h1>Manual metadata page</h1>",
            )

    def test_landing_page_orders_testing_before_enabled_stable(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            manifest = {
                "channels": {
                    "stable": {"branch": "main", "commit": "a" * 40, "packages": {}},
                    "testing": {"branch": "dev", "commit": "b" * 40, "packages": {}},
                }
            }
            write_index(site, manifest, "https://example.github.io/repo")
            html = (site / "index.html").read_text(encoding="utf-8")
            testing = html.index("#[cambonos-testing]")
            stable = html.index("[cambonos]", testing)
            self.assertLess(testing, stable)
            self.assertIn('href="stable/"', html)
            self.assertIn('href="testing/"', html)
            self.assertIn("https://mirror.cambonos.org/stable/$arch", html)
            self.assertIn("https://mirror.cambonos.org/testing/$arch", html)
            self.assertIn('href="metadata/manifest.json"', html)
            self.assertIn('rel="canonical" href="https://example.github.io/repo"', html)
            self.assertIn('<html lang="en">', html)
            self.assertIn('name="description" content="Official CambonOS package repositories, with signed stable and testing channels."', html)
            self.assertIn("Official CambonOS package repositories.", html)
            self.assertIn("Repository channels", html)
            self.assertIn("Channels", html)
            self.assertIn("<th>Channel</th><th>Branch</th><th>Commit</th><th class=\"size\">Packages</th>", html)
            self.assertIn("Repository configuration", html)
            self.assertIn("Testing is disabled by default.", html)
            self.assertIn("Signed global manifest:", html)
            self.assertIn("Official packages / x86_64", html)
            self.assertNotIn("Canales", html)
            self.assertNotIn("Configuración", html)
            self.assertIn("--lime: #aefa50", html)
            self.assertIn(':root[data-theme="dark"]', html)
            self.assertIn("prefers-color-scheme: dark", html)
            self.assertIn('class="theme-toggle"', html)
            self.assertIn('localStorage.setItem("cambonos-theme", preference)', html)
            self.assertIn('class="channel-link stable" href="stable/"', html)
            self.assertIn('aria-label="Change color theme"', html)
            self.assertNotIn("fonts.googleapis.com", html)
            self.assertIn("SigLevel = Required TrustedOnly", html)

    def test_empty_directory_gets_empty_listing(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            empty = site / "empty"
            empty.mkdir()
            generate_directory_indexes(site)
            self.assertIn("This directory is empty.", (empty / "index.html").read_text())


class SiteVerificationTests(unittest.TestCase):
    def _site(self, root: Path):
        package_name = "sample-1-1-any.pkg.tar.zst"
        for channel, branch, section in (
            ("stable", "main", "cambonos"),
            ("testing", "dev", "cambonos-testing"),
        ):
            repository = root / channel / "x86_64"
            repository.mkdir(parents=True)
            archive = repository / package_name
            archive.write_bytes((channel + " package").encode())
            signature = Path(str(archive) + ".sig")
            signature.write_bytes((channel + " signature").encode())
            for filename in (
                f"{section}.db", f"{section}.db.sig",
                f"{section}.db.tar.gz", f"{section}.db.tar.gz.sig",
                f"{section}.files", f"{section}.files.sig",
                f"{section}.files.tar.gz", f"{section}.files.tar.gz.sig",
            ):
                (repository / filename).write_bytes(filename.encode())
            record = {
                "version": "1-1", "source_hash": "a" * 64,
                "package_hash": sha256_file(archive),
                "package_file": package_name,
                "signature_hash": sha256_file(signature),
            }
            channel_manifest = root / channel / "manifest.json"
            channel_manifest.write_text("{}")
            Path(str(channel_manifest) + ".sig").write_bytes(b"manifest signature")
            (root / channel / "index.html").write_text("index")
            (repository / "index.html").write_text("index")
            if channel == "stable":
                stable_record = record
            else:
                testing_record = record
        metadata = root / "metadata"
        metadata.mkdir()
        (metadata / "manifest.json").write_text(json.dumps({
            "channels": {
                "stable": {"packages": {"sample": stable_record}},
                "testing": {"packages": {"sample": testing_record}},
            }
        }))
        Path(str(metadata / "manifest.json") + ".sig").write_bytes(b"global signature")
        (metadata / "index.html").write_text("index")
        (root / "index.html").write_text("landing")

    def test_verify_site_accepts_complete_consistent_tree(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            verify_site(site)

    def test_verify_site_rejects_package_hash_mismatch(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            (site / "stable" / "x86_64" / "sample-1-1-any.pkg.tar.zst").write_bytes(b"tampered")
            with self.assertRaisesRegex(CambonosError, "SHA256 incorrecto"):
                verify_site(site)

    def test_verify_site_rejects_missing_package_signature(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            (site / "testing" / "x86_64" / "sample-1-1-any.pkg.tar.zst.sig").unlink()
            with self.assertRaisesRegex(CambonosError, "falta la firma"):
                verify_site(site)

    def test_verify_site_rejects_package_set_mismatch(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            (site / "stable" / "x86_64" / "unexpected-1-1-any.pkg.tar.zst").write_bytes(b"extra")
            with self.assertRaisesRegex(CambonosError, "no coinciden con el manifiesto"):
                verify_site(site)

    def test_verify_site_rejects_missing_repository_database_member(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            (site / "stable" / "x86_64" / "cambonos.files.tar.gz.sig").unlink()
            with self.assertRaisesRegex(CambonosError, "falta el archivo de repositorio"):
                verify_site(site)

    def test_verify_site_rejects_symlinks(self):
        with tempfile.TemporaryDirectory() as temporary:
            site = Path(temporary)
            self._site(site)
            (site / "stable" / "x86_64" / "link").symlink_to("sample-1-1-any.pkg.tar.zst")
            with self.assertRaisesRegex(CambonosError, "enlaces simbólicos"):
                verify_site(site)

    def test_write_site_metadata_requires_both_channels(self):
        with tempfile.TemporaryDirectory() as temporary:
            with self.assertRaises(CambonosError):
                write_site_metadata(Path(temporary), {"stable": {}}, "https://example.invalid")

    def test_write_site_metadata_requires_https(self):
        with tempfile.TemporaryDirectory() as temporary:
            channels = {
                name: {"branch": branch, "commit": "a" * 40, "packages": {},
                       "build_environment": {}, "image": "arch-image"}
                for name, branch in (("stable", "main"), ("testing", "dev"))
            }
            with self.assertRaises(CambonosError):
                write_site_metadata(Path(temporary), channels, "http://example.invalid")


